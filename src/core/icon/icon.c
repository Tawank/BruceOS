typedef struct {
    const char *name;
    bruce_icon_t icon;
} icon__entry_t;

#define ICON__ENTRY(icon_name, icon_bits) \
    { icon_name, { BRUCE_ICON_SIZE, BRUCE_ICON_SIZE, icon_bits } }

static const icon__entry_t s_icons[] = {
    ICON__ENTRY("wifi", s_icon_wifi),
    ICON__ENTRY("ble", s_icon_bluetooth),
    ICON__ENTRY("remote", s_icon_ir),
    ICON__ENTRY("handheld", s_icon_handheld),
    ICON__ENTRY("folder", s_icon_folder),
    ICON__ENTRY("files", s_icon_folder),
    ICON__ENTRY("terminal", s_icon_terminal),
    ICON__ENTRY("clock", s_icon_clock),
    ICON__ENTRY("settings", s_icon_settings),
    ICON__ENTRY("selftest", s_icon_selftest),
    ICON__ENTRY("apps", s_icon_apps),
};

const bruce_icon_t *icon__get(const char *name) {
    if (name == NULL) { return NULL; }
    for (size_t i = 0; i < (sizeof(s_icons) / sizeof(s_icons[0])); ++i) {
        if (strcmp(name, s_icons[i].name) == 0) { return &s_icons[i].icon; }
    }
    return NULL;
}
