/* -------------------------------------------------------------------------- */
/* Built-in font: fixed 5-wide bitmap glyphs, ASCII 32-126 plus the Latin-1   */
/* Supplement / Latin Extended-A subset this project has historically needed */
/* (Western/Central European accented letters, common quote glyphs).         */
/*                                                                            */
/* Earlier revisions rendered an accented letter by drawing the plain ASCII  */
/* base glyph and stamping a hardcoded accent shape on top of it at draw     */
/* time. That collided with the base glyph's own ink for most accented      */
/* capitals -- e.g. E/O/C/S/Z/I fill row 0 solid, so an acute/grave/caron/   */
/* diaeresis drawn there just disappeared into (or smudged) the letter's top */
/* stroke instead of reading as a separate mark.                             */
/*                                                                            */
/* Every glyph here is a real, static per-codepoint bitmap instead: rows 0-1 */
/* of the cell are reserved (every s_ascii/s_extended entry has them blank)  */
/* so a diacritic always has genuine headroom, the same way lowercase        */
/* ascenders already did in the old font (x-height letters left rows 0-1     */
/* blank; capitals didn't). That makes a collision structurally impossible   */
/* rather than something to hand-verify per accent/letter combination.       */
/*                                                                            */
/* Generated by tools/gen_display_font.py -- regenerate with that script     */
/* rather than hand-editing the tables below. */
/* -------------------------------------------------------------------------- */

typedef struct {
    uint16_t codepoint;
    display__column_t columns[DISPLAY_FONT__WIDTH];
} display__extended_glyph_t;

typedef struct {
    uint16_t codepoint;
    char ascii;
} display__alias_glyph_t;

