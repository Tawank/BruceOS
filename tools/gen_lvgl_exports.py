#!/usr/bin/env python3
"""Lists LVGL's public API as ELF loader exports.

Reads lvgl.h already run through the C preprocessor with Bruce's lv_conf.h,
so only what the configuration enables is listed, and writes one
ESP_ELFSYM_EXPORT() line per function or extern variable named lv_*. The
firmware build runs it (src/CMakeLists.txt); the output is included into the
ELF loader's symbol table.

    gen_lvgl_exports.py <preprocessed lvgl.h> <output .inc>
"""

import re
import sys

# Not for apps: Core sets LVGL up per process and supplies its memory hooks
# (core/lvgl/lvgl_port.c); lv_global_default() is exported by hand.
NOT_EXPORTED = {
    "lv_init",
    "lv_deinit",
    "lv_global_default",
    "lv_mem_init",
    "lv_mem_deinit",
    "lv_mem_add_pool",
    "lv_mem_remove_pool",
    "lv_malloc_core",
    "lv_realloc_core",
    "lv_free_core",
    "lv_mem_monitor_core",
    "lv_mem_test_core",
    "lv_tick_set_cb",
    "lv_delay_set_cb",
    # Keeps its last run in a static shared by every process; apps call lvgl__step().
    "lv_timer_handler_run_in_period",
}
# Internals apps have no use for; leaving them out also lets the linker drop
# whatever nothing else in the firmware uses.
NOT_EXPORTED_PREFIXES = (
    "lv_draw_sw_",
    "lv_cache_",
    "lv_image_cache_",
    "lv_image_header_cache_",
    "lv_image_decoder_",
    "lv_ll_",
    "lv_rb_",
    "lv_iter_",
    "lv_circle_buf_",
    "lv_lru_",
    "lv_thread_",
    "lv_mutex_",
    "lv_lock",
    "lv_unlock",
    "lv_fs_",
    "lv_profiler_",
    "lv_mem_",
)


def strip_bodies(text):
    """Replaces every {...} with {} so struct members and inline bodies vanish."""
    out = []
    depth = 0
    for char in text:
        if char == "{":
            if depth == 0:
                out.append("{")
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                out.append("}")
        elif depth == 0:
            out.append(char)
    return "".join(out)


def public_names(text):
    names = set()
    for statement in re.split(r"[;}]", strip_bodies(text)):
        statement = " ".join(statement.split())
        if not statement or statement.startswith("typedef") or re.search(r"\bstatic\b", statement):
            continue
        if "{" in statement:
            continue
        function = re.match(r"^[\w\s\*]*?\b(lv_\w+)\s*\(", statement)
        if function:
            names.add(function.group(1))
            continue
        variable = re.match(r"^extern\b[\w\s\*]*?\b(lv_\w+)\s*(\[[^\]]*\])?$", statement)
        if variable:
            names.add(variable.group(1))
    return sorted(n for n in names - NOT_EXPORTED if not n.startswith(NOT_EXPORTED_PREFIXES))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    names = public_names(open(sys.argv[1], encoding="utf-8").read())
    with open(sys.argv[2], "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/gen_lvgl_exports.py; do not edit. */\n")
        for name in names:
            out.write(f"ESP_ELFSYM_EXPORT({name}),\n")


if __name__ == "__main__":
    main()
